import argparse
import csv
import re
from pathlib import Path

TEST_FOLDERS = re.compile(r"/(?:test|tests|__tests__|__mocks__|__fixtures__|fixtures|test-utils)(?:/|$)")
TEST_FILES = re.compile(r"\.(?:test|spec)\.[cm]?[jt]sx?$")
BUILD_FOLDERS = re.compile(r"/(?:dist|build|coverage)(?:/|$)")
WOFF2_FILE = "/packages/excalidraw/subset/woff2/woff2-bindings.ts"


def include_row(row, exclude_woff2=False):
    path = (row.get("File") or "").replace("\\", "/").lower()
    if "/node_modules/" in path:
        return False
    if not ("/excalidraw/packages/" in path or "/excalidraw/excalidraw-app/" in path):
        return False
    if not path.endswith((".ts", ".tsx")):
        return False
    if TEST_FOLDERS.search(path) or TEST_FILES.search(path) or BUILD_FOLDERS.search(path):
        return False
    if exclude_woff2 and path.endswith(WOFF2_FILE):
        return False
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="CSV exported from SciTools Understand")
    parser.add_argument("--exclude-woff2", action="store_true", help="Additionally omit suspected generated woff2-bindings.ts")
    args = parser.parse_args()

    src = args.input
    suffix = "_filtered_production_no_woff2.csv" if args.exclude_woff2 else "_filtered_production.csv"
    dst = src.with_name(src.stem + suffix)
    total = kept = removed_node_modules = 0

    with src.open("r", encoding="utf-8-sig", newline="") as infile, dst.open("w", encoding="utf-8-sig", newline="") as outfile:
        reader = csv.DictReader(infile)
        if not reader.fieldnames or "File" not in reader.fieldnames:
            raise ValueError("Missing 'File' column in the CSV export")
        writer = csv.DictWriter(outfile, fieldnames=reader.fieldnames)
        writer.writeheader()
        for row in reader:
            total += 1
            if "/node_modules/" in (row.get("File") or "").replace("\\", "/").lower():
                removed_node_modules += 1
            if include_row(row, exclude_woff2=args.exclude_woff2):
                writer.writerow(row)
                kept += 1

    print(f"Original rows: {total:,}")
    print(f"Rows in node_modules: {removed_node_modules:,}")
    print(f"Rows retained: {kept:,}")
    print(f"Saved to: {dst.resolve()}")


if __name__ == "__main__":
    main()
